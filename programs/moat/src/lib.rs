//! # Moat
//!
//! A non-custodial Solana vault that holds the funds and enforces the limits
//! while a TEE (the *keep*) holds the strategy and signs trade intents.
//!
//! The architecture is one sentence: **the keep decides, the moat permits.**
//! Nothing the keep produces is trusted; every intent is re-checked against
//! owner-set policy using the chain's own oracle reads before a lamport moves,
//! and the owner's withdrawal path never touches the keep at all.
//!
//! Component naming follows the fortress the project is named for — `keep`
//! (enclave), `portcullis` (the intent gate), `signet` (attestation), `drawbridge`
//! (deposits/withdrawals), `sortie` (one execution leg), `spyglass` (dashboard).
//! The instruction names stay conventional on purpose: cute selectors cost
//! reviewer trust, and this is a program that wants to be read.

